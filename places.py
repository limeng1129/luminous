# 淡淡的参照点：帮你判断自己的光点大概在世界的哪一块
ANCHORS = ["北京", "上海", "东京", "新加坡", "迪拜", "巴黎", "伦敦",
           "莫斯科", "纽约", "洛杉矶", "悉尼", "开罗", "里约"]

# 长的地名优先匹配，避免「上海」被「海」抢走
_SORTED = sorted(PLACES.keys(), key=len, reverse=True)


def lookup(text):
    """从一段文字里认出地名。认不出返回 None。"""
    if not text:
        return None
    t = str(text)
    for name in _SORTED:
        if name in t:
            return name
    return None


def collect(posts, photos):
    """把文章和照片按地点归拢，返回可以直接画到地图上的数据。"""
    spots = {}

    def touch(name):
        if name not in spots:
            lat, lng = PLACES[name]
            spots[name] = {"name": name, "lat": lat, "lng": lng,
                           "posts": [], "photos": [], "first": None}
        return spots[name]

    for p in posts:
        name = lookup(p.get("place")) or lookup(p.get("title"))
        if not name:
            continue
        s = touch(name)
        s["posts"].append({"slug": p["slug"], "title": p["title"],
                           "date": (p.get("created_at") or "")[:10]})
        if s["first"] is None:
            s["first"] = p.get("created_at") or ""

    for ph in photos:
        name = lookup(ph.get("subtitle")) or lookup(ph.get("title"))
        if not name:
            continue
        s = touch(name)
        s["photos"].append({"id": ph["id"], "src": ph["src"],
                            "title": ph["title"], "subtitle": ph.get("subtitle") or ""})

    out = []
    for s in spots.values():
        s["count"] = len(s["posts"]) + len(s["photos"])
        out.append(s)
    # 按去过的密度排，画图时大的先画在下面
    out.sort(key=lambda s: -s["count"])

    anchors = [{"name": n, "lat": PLACES[n][0], "lng": PLACES[n][1]}
               for n in ANCHORS if n not in spots]

    return {"spots": out, "anchors": anchors,
            "unknown": _unmatched(posts, photos)}


def _unmatched(posts, photos):
    """有写地点但没认出来的，列出来提示用户。"""
    miss = set()
    for p in posts:
        raw = (p.get("place") or "").strip()
        if raw and not lookup(raw):
            miss.add(raw.split("·")[0].strip()[:20])
    for ph in photos:
        raw = (ph.get("subtitle") or "").strip()
        if raw and not lookup(raw):
            miss.add(raw.split("·")[0].strip()[:20])
    return sorted(x for x in miss if x)[:12]
